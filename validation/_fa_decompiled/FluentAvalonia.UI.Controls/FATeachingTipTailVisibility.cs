namespace FluentAvalonia.UI.Controls;

/// <summary>
/// Defines constants that specify whether a <see cref="T:FluentAvalonia.UI.Controls.FATeachingTip" />'s Tail is visible or collapsed.
/// </summary>
public enum FATeachingTipTailVisibility
{
	/// <summary>
	/// The teaching tip's tail is collapsed when non-targeted and visible when the targeted.
	/// </summary>
	Auto,
	/// <summary>
	/// The teaching tip's tail is visible.
	/// </summary>
	Visible,
	/// <summary>
	/// The teaching tip's tail is collapsed.
	/// </summary>
	Collapsed
}
